export type CredentialStatus = {
  present: boolean;
  last4: string | null;
  updatedAt: string | null;
};

/**
 * Which of a provider's values is being addressed.
 *
 * Most providers have one credential and pass nothing: the bare provider id is
 * the keyring account name, which is what every key stored before slots existed
 * uses. LiveKit is the exception -- it needs a server URL, an API key and an API
 * secret, and they are not interchangeable. The slot is the environment variable
 * the value belongs in, so each of the three is stored and read separately.
 *
 * This is a variable *name*. No value ever crosses back out of Rust; a status is
 * presence plus at most four trailing characters.
 */
export function setCredential(
  provider: string,
  secret: string,
  slot?: string,
): Promise<CredentialStatus> {
  return call<CredentialStatus>("set_credential", { provider, secret, slot: slot ?? null });
}

export function deleteCredential(provider: string, slot?: string): Promise<void> {
  return call<void>("delete_credential", { provider, slot: slot ?? null });
}

export function getCredentialStatus(
  provider: string,
  slot?: string,
): Promise<CredentialStatus> {
  return call<CredentialStatus>("get_credential_status", { provider, slot: slot ?? null });
}

/**
 * What a connectivity test concluded.
 *
 * Three values, not two. `rejected` is the only one that means the credential is
 * at fault: `inconclusive` covers a provider outage and a malformed request of
 * ours, and telling a user their key is broken in either case would send them to
 * re-enter a working credential.
 */
export type ProbeVerdict = "valid" | "rejected" | "inconclusive" | "no_probe" | "no_secret";

export type ProbeOutcome = {
  provider: string;
  verdict: ProbeVerdict;
  status?: number;
  latencyMs?: number;
  /** A short provider message, or why nothing could be concluded. Never a secret. */
  detail?: string;
};

export function testProviderCredential(provider: string): Promise<ProbeOutcome> {
  return call<ProbeOutcome>("test_provider_credential", { provider });
}

/**
 * The worker's status, as `get_agent_status` returns it.
 *
 * The type itself lives in `lib/agentRuntime.ts` rather than here, because the
 * `agent_*` events carry the identical object and a second declaration of one
 * Rust struct is how an event payload and a polled payload come to disagree
 * without anybody noticing. It is a type-only import, so it costs nothing at
 * runtime and creates no cycle with the hook that lives beside it.
 */
export function getAgentStatus(): Promise<AgentStatus> {
  return call<AgentStatus>("get_agent_status");
}
