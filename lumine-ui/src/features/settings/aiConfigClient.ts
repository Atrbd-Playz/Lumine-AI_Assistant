/** Whether one variable of a multi-part credential has a value. */
export type CredentialSlotStatus = {
  /** The variable this value belongs in. Doubles as the keyring slot name. */
  env: string;
  label: string;
  kind: "secret" | "url" | "text";
  help: string;
  /** A value is held in the OS keyring for this variable specifically. */
  stored: boolean;
  /** At most the final four characters, so three similar keys can be told apart. */
  storedLast4: string | null;
  /** A value is set in the environment for this variable specifically. */
  inEnv: boolean;
};

/** One provider the active profile cannot run without. */
export type RequiredCredential = {
  id: string;
  label: string;
  /** Where to get a key. Opened by the onboarding screen's button. */
  setupUrl?: string;
  /**
   * Environment variable *names* the worker reads. Never a value -- these are
   * documentation, and they are the only thing a user can act on when
   * configuring through `agent/.env` instead of this wizard.
   */
  keyEnv: string[];
  /**
   * One entry per `keyEnv` variable, in the same order, so the wizard draws a
   * field for each. Falls back to a single field derived from `keyEnv` when the
   * desktop layer is older and does not send them.
   */
  keySlots: {
    /** The variable the value belongs in. Doubles as the keyring slot name. */
    env: string;
    label: string;
    kind: "secret" | "url" | "text";
    help: string;
  }[];
  /**
   * Per-variable state, in the same order as `keySlots`.
   *
   * Without this a provider holding two of three values is undrawable: the
   * wizard can only show a field, and an empty field next to a stored one is
   * indistinguishable from having stored nothing. That is the shape behind
   * "it saved all three, but the last two were empty" and "reopening it showed
   * three empty fields" -- saving one value closed the whole group and the
   * group gave no credit for it.
   *
   * Empty on an older desktop layer, which is why every consumer falls back to
   * deriving slots from `keySlots`.
   */
  slots: CredentialSlotStatus[];
  /** What this provider is doing in the profile, for a subtitle. */
  capabilities: string[];
  /**
   * **Any** of this provider's variables is held in the OS keyring.
   *
   * A badge signal, and deliberately weaker than `missing.length === 0`. It is
   * true the moment one of LiveKit's three values lands, so nothing that decides
   * whether a call can be attempted may read it.
   */
  stored: boolean;
  storedLast4: string | null;
  inEnv: boolean;
  /** A local provider needs no credential at all, like Silero. */
  local: boolean;
  /**
   * Which of this provider's variables still have no value anywhere.
   *
   * A provider with one key is satisfied when this is empty or holds that one
   * name. A provider with several -- LiveKit needs a server address, an API key
   * and an API secret -- is only satisfied when it is empty, because two of
   * three is a credential that cannot connect.
   *
   * The gate used to ask only whether *any* value existed for the provider, which
   * is why it reported a LiveKit install with nothing usable as ready.
   */
  missing: string[];
};

export type SetupStatus = {
  required: RequiredCredential[];
  /** The single boolean the voice path gates on. */
  ready: boolean;
  activeProfile: string | null;
  /** True when a saved document governs rather than `agent/.env`. */
  configuredInApp: boolean;
  /** Why the configuration itself is not usable, in the worker's own words. */
  blocking: string[];
};

/**
 * Whether this install can hold a conversation yet.
 *
 * One call, because the answer needs the provider catalog, the keyring and the
 * worker's own validation, and assembling it in the webview would mean
 * reimplementing the reduction in TypeScript where it could disagree with the
 * worker. It reports *presence*, not validity: proving a key works costs a
 * billable request to a third party, and the Providers page has an explicit
 * "Test" for that.
 */
export function getSetupStatus(): Promise<SetupStatus> {
  return call<SetupStatus>("get_setup_status");
}

