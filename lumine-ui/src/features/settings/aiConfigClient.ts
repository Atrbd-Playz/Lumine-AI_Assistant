import { invoke } from "@tauri-apps/api/core";
import type { AgentStatus } from "../../lib/agentRuntime";
import type { ConfigDocument, Diagnostic, ProviderCatalog } from "./aiConfigTypes";

/**
 * Every Tauri call the AI Control Center makes.
 *
 * The settings surface never talks to Python, LiveKit, or a provider directly.
 * Two boundaries matter:
 *
 * - **Credentials are write-only.** `setCredential` takes a secret and returns
 *   redacted status; `getCredentialStatus` returns presence and a last-four tail.
 *   There is deliberately no function here that reads a stored secret back.
 * - **Validation is server-side.** The worker owns the capability rules, so the UI
 *   renders the diagnostics it returns rather than deciding validity itself.
 */

export class DesktopUnavailableError extends Error {
  constructor() {
    super("This screen needs the Lumine desktop app. Run `npm run tauri dev`.");
    this.name = "DesktopUnavailableError";
  }
}

/**
 * The catalog shape this screen was written against. See `agent/providers.py`.
 *
 * v9 added a probe's `authKind`/`tokenPath`, which is how LiveKit became
 * testable: its credential is a URL, an API key and an API secret used together
 * to mint a token, so a probe that puts one value in one header could not check
 * it.
 *
 * v10 added a per-option `advanced` flag, so a stage leads with the settings a
 * person chooses and puts token caps and sampling knobs behind a disclosure. It
 * is declared in the catalog because only the catalog knows whether a
 * `temperature` is ordinary on one model and meaningless on another.
 *
 * v11 added each model's `inputModalities`, so Diagnostics can report what a
 * model can be given and the camera control can decline to offer itself to a
 * stack whose frames would arrive nowhere.
 *
 * v12 added a per-option `default` and `hidden`, and the local-model provider
 * that needs them. Ollama's OpenAI-compatible server has no authentication, but
 * the OpenAI client refuses to construct without a key, so Lumine sends the
 * literal string `"ollama"`. That argument has to reach the plugin while staying
 * out of the screen: a required value the user cannot usefully change is not a
 * setting, and drawing it would present a non-problem as a setup step.
 *
 * Bump in step with `CATALOG_VERSION` in `agent/providers.py`; a test asserts the
 * two agree.
 */
const CATALOG_VERSION = 12;

export class CatalogTooNewError extends Error {
  constructor(received: number) {
    super(
      `The agent ships a provider catalog this build does not understand (v${received}, expected v${CATALOG_VERSION}). Update the app.`,
    );
    this.name = "CatalogTooNewError";
  }
}

/**
 * Refuse a catalog this screen was not written for.
 *
 * The catalog is the only description of what providers, models, and voices
 * exist. Reading a field that is not there would throw somewhere deep in a
 * render, which is a confusing way to learn the agent and the app disagree.
 */
function assertCatalogVersion(catalog: ProviderCatalog): ProviderCatalog {
  if (typeof catalog?.version !== "number") {
    throw new CatalogTooNewError(Number.NaN);
  }
  if (catalog.version > CATALOG_VERSION) {
    throw new CatalogTooNewError(catalog.version);
  }
  return catalog;
}

function isTauri(): boolean {
  return typeof window !== "undefined" && "__TAURI_INTERNALS__" in window;
}

/** Run a Tauri command, turning "not running inside the app" into a clear error. */
async function call<T>(command: string, args?: Record<string, unknown>): Promise<T> {
  if (!isTauri()) throw new DesktopUnavailableError();
  return invoke<T>(command, args);
}

export async function getProviderCatalog(): Promise<ProviderCatalog> {
  return assertCatalogVersion(await call<ProviderCatalog>("get_provider_catalog"));
}

/**
 * One thing Lumine can do, as a person would describe it.
 *
 * Generated by `agent/tool_catalog.py` from the same registry the worker hands to
 * the model, so a tool cannot appear here without being callable. The docstring
 * on each tool is the model's schema and is deliberately not what this shows.
 */
export type CatalogTool = {
  /** The exact id the model is given, so a report can be matched to a call. */
  id: string;
  label: string;
  summary: string;
  /**
   * The id of one `ToolCategory`.
   *
   * Not a free word. The page builds its tab strip from the published category
   * list, so a value the worker has not declared would put a card behind a tab
   * that does not exist. `agent/tool_catalog.py --check` fails on that.
   */
  category: string;
  /**
   * `"answers"` only tells Lumine something. `"opens"` acts on this machine.
   *
   * The distinction is stated rather than left to the name, because it is the
   * thing a person is deciding about when they leave a tool switched on.
   */
  effect: "answers" | "opens";
  /** Whether reaching it involves the internet. */
  network: boolean;
  parameters: {
    name: string;
    kind: string;
    required: boolean;
    help: string;
  }[];
  /** False when an environment toggle has switched it off for this run. */
  enabled: boolean;
  /** Which toggle did it. Empty when enabled. */
  disabledReason: string;
};

/**
 * One group on the Tools page tab strip.
 *
 * Declared in `agent/tools/tools_registry.py` and published, order included, so
 * the strip is not alphabetical accident. The `description` is what the strip's
 * own `Hint` says: a tab that is only a word makes the reader guess what belongs
 * in it, and a card has nowhere to go if the group is misread.
 */
export type ToolCategory = {
  id: string;
  label: string;
  description: string;
};

export type ToolCatalog = {
  version: number;
  categories: ToolCategory[];
  tools: CatalogTool[];
};

/** Every tool, plus the groups they fall into. */
export type ToolCatalogResult = {
  categories: ToolCategory[];
  tools: CatalogTool[];
};

/**
 * What Lumine can currently do.
 *
 * A command failure resolves to empty lists rather than throwing: the Tools page
 * is a read-only view, and a Python helper that will not start should leave it
 * saying it does not know yet, not replace the workspace with an error. The
 * desktop layer caches the answer for the life of the process, so this is one
 * cold Python start and then an immediate read.
 */
export async function getToolCatalog(): Promise<ToolCatalogResult> {
  try {
    const catalog = await call<ToolCatalog>("get_tool_catalog");
    return {
      categories: Array.isArray(catalog.categories) ? catalog.categories : [],
      tools: Array.isArray(catalog.tools) ? catalog.tools : [],
    };
  } catch {
    return { categories: [], tools: [] };
  }
}

/**
 * One model a local server is serving.
 *
 * `size` is bytes and is present only when the server bothered to say. It is not
 * decoration: `llama3.2:3b` and a 70B model are the same number of characters to
 * somebody who has to guess what will fit in their memory, and the size is the
 * only thing in this app that can tell them.
 */
export type LocalModel = {
  id: string;
  size?: number;
};

export type LocalModelDiscovery = {
  /** Whether the server was reached. Says nothing about whether it has models. */
  ok: boolean;
  /** The address that was asked, so a person can check it against their server. */
  baseUrl: string;
  /** Which route answered, or empty when none did. */
  route: string;
  latencyMs: number;
  models: LocalModel[];
  /** A machine status, when there is one worth reporting. */
  error: string;
  /** The same thing in words a person can act on. */
  detail: string;
};

/**
 * Ask a local model server what it has.
 *
 * Resolves rather than rejects on a failed lookup, because failing *is* an answer
 * here: a server that is not running produces a sentence saying so, which is
 * exactly what the chooser needs. Only a desktop layer that is not there at all
 * rejects.
 */
export async function discoverLocalModels(baseUrl?: string): Promise<LocalModelDiscovery> {
  const trimmed = (baseUrl ?? "").trim();
  return call<LocalModelDiscovery>("discover_local_models", trimmed ? { baseUrl: trimmed } : {});
}

