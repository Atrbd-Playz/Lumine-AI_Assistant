/** The stage a preview renders, which is not necessarily the saved one. */
export type VoicePreviewRequest = {
  provider: string;
  model: string;
  voice?: string;
  options?: Record<string, string>;
};

export type VoicePreview = {
  /** A `data:` URI, ready for `HTMLAudioElement.src`. */
  dataUri: string;
  mimeType: string;
  sampleRate: number;
  channels: number;
  durationSeconds: number;
};

/**
 * Speak a short phrase with these exact settings, without saving them.
 *
 * A talking-speed slider is only usable if you can hear what it does. This takes
 * the *draft* stage, so a preview reflects an unsaved change — which is the whole
 * reason to have one. The synthesis goes through the worker's own stage builder, so
 * what you hear is the voice the session will use rather than an approximation of
 * it, and no room, agent, or session is involved.
 *
 * The credential never reaches here: it is read from the keyring on the Rust side
 * and put in the child process's environment. This request carries ids, numbers
 * and enum names only.
 */
export function previewVoice(request: VoicePreviewRequest, text?: string): Promise<VoicePreview> {
  return call<VoicePreview>("preview_voice", {
    fragment: { ...request, options: request.options ?? {} },
    text: text ?? null,
  });
}
